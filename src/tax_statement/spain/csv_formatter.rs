    fn write_carryforward<W: Write>(
        writer: &mut W,
        statement: &SpanishTaxStatement,
    ) -> GenericResult<()> {
        let groups = [
            ("RCM", &statement.rcm_ledger_next, statement.rcm_expired),
            ("GYP", &statement.gyp_ledger_next, statement.gyp_expired),
        ];

        if groups
            .iter()
            .all(|(_, ledger, expired)| ledger.is_empty() && expired.is_zero())
        {
            return Ok(());
        }

        writeln!(writer)?;
        writeln!(
            writer,
            "# SALDOS NEGATIVOS PENDIENTES — put these in next year's taxes.spain.loss_carryforward,"
        )?;
        writeln!(
            writer,
            "# keyed by the year each arose in. A balance may be offset only in the four following"
        )?;
        writeln!(writer, "# years, so the origin year is part of the data.")?;

        for (group, ledger, expired) in groups {
            for (origin, amount) in ledger.balances() {
                writeln!(
                    writer,
                    "CARRYFORWARD_{group}_{origin},Saldo negativo pendiente — {group} — origen {origin},{}",
                    Self::format_decimal(*amount)
                )?;
            }
            if expired > Decimal::ZERO {
                writeln!(
                    writer,
                    "CARRYFORWARD_{group}_EXPIRED,Saldo negativo caducado sin usar ({group}),{}",
                    Self::format_decimal(expired)
                )?;
            }
        }

        Ok(())
    }

    fn write_deferred_losses<W: Write>(
        writer: &mut W,
        statement: &SpanishTaxStatement,
    ) -> GenericResult<()> {
        if statement.deferred_losses_next.is_empty() {
            return Ok(());
        }

        writeln!(writer)?;
        writeln!(
            writer,
            "# PÉRDIDAS DIFERIDAS PENDIENTES — put these in next year's taxes.spain.deferred_losses."
        )?;
        writeln!(
            writer,
            "# Each is a loss still blocked by homogeneous securities bought inside the two-month"
        )?;
        writeln!(
            writer,
            "# window and not yet disposed of; it becomes deductible as those shares are sold."
        )?;

        for (index, deferred) in statement.deferred_losses_next.iter().enumerate() {
            let label = format!(
                "{} — {} shares acquired {} blocking the loss of {}",
                deferred.symbol,
                deferred.blocked_quantity.normalize(),
                Self::format_date(deferred.acquisition_date),
                Self::format_date(deferred.sale_date)
            );
            writeln!(
                writer,
                "DEFERRED_LOSS_{index},{},{}",
                Self::escape_csv(&label),
                Self::format_decimal(deferred.loss)
            )?;
        }

        Ok(())
    }

