/// One casilla of the filer's return, with the amount that goes in it.
pub(super) struct FormBox {
    /// Stable key the CSV row is named by, e.g. `MODELO_109_HOJA_28`.
    pub key: String,
    /// Form the casilla belongs to, as the filer knows it.
    pub form: &'static str,
    /// Casilla as the form prints it: a number, a sum of two (`06+16`), a range, or a number with
    /// the box that repeats it.
    pub casilla: String,
    /// Sheet the casilla lives on where the form has more than one numbering space (`hoja`,
    /// `anexo 3`); empty otherwise.
    pub sheet: &'static str,
    /// What the form calls the amount.
    pub concept: String,
    pub value: Decimal,
}

impl FormBox {
    fn new(
        key_prefix: &str,
        form: &'static str,
        sheet: &'static str,
        casilla: &str,
        concept: &str,
        value: Decimal,
    ) -> FormBox {
        FormBox {
            key: format!("{key_prefix}{casilla}"),
            form,
            casilla: casilla.to_owned(),
            sheet,
            concept: concept.to_owned(),
            value,
        }
    }

    /// The label the CSV prints: the concept, plus the sheet and casilla where the form numbers
    /// more than one space and the bare concept would not say which one.
    pub fn label(&self) -> String {
        if self.sheet.is_empty() {
            self.concept.clone()
        } else {
            format!(
                "{} ({}, casilla {})",
                self.concept, self.sheet, self.casilla
            )
        }
    }
}

/// Every casilla of one regime's return, with the caveats that qualify it.
///
/// The header and footer lines are stored one per printed line, exactly as the CSV breaks them: the
/// CSV prefixes each with `# `, and the report joins them into prose.
pub(super) struct FormMapping {
    pub title: &'static str,
    pub header_lines: Vec<String>,
    pub boxes: Vec<FormBox>,
    pub footer_lines: Vec<String>,
    /// The retenciones casilla foreign withholding must **not** be entered in.
    pub withholding_casilla: String,
}

/// The return the regime files, as the filer knows it.
pub(super) fn form_name(regime: SpanishTaxRegime) -> &'static str {
    match regime {
        SpanishTaxRegime::Gipuzkoa => "Modelo 109",
        SpanishTaxRegime::Comun => "Modelo 100",
        SpanishTaxRegime::Navarra => "Modelo F-93",
    }
}

/// The casillas of the filer's own return.
pub(super) fn form_mapping(statement: &SpanishTaxStatement) -> FormMapping {
    match statement.regime {
        SpanishTaxRegime::Gipuzkoa => modelo_109_mapping(statement),
        SpanishTaxRegime::Comun => modelo_100_mapping(statement),
        SpanishTaxRegime::Navarra => modelo_f93_mapping(statement),
    }
}

fn modelo_109_mapping(statement: &SpanishTaxStatement) -> FormMapping {
    let layout = modelo_109::layout(statement.year);

    let mut header_lines = vec![
        "The numbers below are read off the Hacienda Foral \"Propuesta de autoliquidación\""
            .to_owned(),
        format!(
            "specimen for ejercicio {} (gipuzkoa.eus/es/web/ogasuna/impuestos/modelo/109/,",
            layout.ejercicio
        ),
        "retrieved 2026-08-11). Gipuzkoa publishes no blank numbered form — the return".to_owned(),
        "is generated by Zergabidea — so check each casilla against your own proposal.".to_owned(),
    ];

    if statement.year > layout.ejercicio {
        header_lines.push(format!(
            "WARNING: no form is published for ejercicio {} yet — it is filed in {}.",
            statement.year,
            statement.year + 1
        ));
        header_lines.push(format!(
            "These are the ejercicio-{} numbers, the last published layout.",
            layout.ejercicio
        ));
    }

    let mut boxes = Vec::new();

    if layout.anexo3 {
        for (casilla, concept, value) in [
            (
                modelo_109::ANEXO3_RCM_GROSS,
                "Rendimientos íntegros del capital mobiliario (excluida la renta exenta)",
                statement.declarable_rcm_income(),
            ),
            (
                modelo_109::ANEXO3_RCM_EXPENSES,
                "Gastos deducibles del capital mobiliario",
                statement.total_deductible_fees,
            ),
        ] {
            boxes.push(FormBox::new(
                "MODELO_109_ANEXO3_",
                form_name(SpanishTaxRegime::Gipuzkoa),
                "anexo 3",
                casilla,
                concept,
                value,
            ));
        }
    } else {
        header_lines.extend(
            [
                "WARNING: the rendimientos íntegros / gastos breakdown lives in Anexo 3,",
                "whose internal numbering is confirmed only through ejercicio 2024 and was",
                "renumbered by NF 1/2025. Only the Hoja de liquidación rows are emitted",
                "here; take the breakdown from your own Anexo 3.",
            ]
            .map(str::to_owned),
        );
    }

    for (casilla, concept, value) in [
        (
            modelo_109::HOJA_RCM_NET,
            "Rendimiento neto del capital mobiliario (base del ahorro)",
            statement.rcm_net,
        ),
        (
            modelo_109::HOJA_RCM_COMPENSATION,
            "Compensación de rendimientos negativos de ejercicios anteriores",
            statement.rcm_own_group_losses_applied(),
        ),
        (
            modelo_109::HOJA_CAPITAL_GAINS,
            "Ganancias y pérdidas patrimoniales por transmisiones",
            statement.gyp_net,
        ),
        (
            modelo_109::HOJA_GYP_COMPENSATION,
            "Compensación de pérdidas de ejercicios anteriores",
            statement.gyp_own_group_losses_applied(),
        ),
        (
            modelo_109::HOJA_SAVINGS_BASE,
            "Base liquidable del ahorro (tras compensación)",
            statement.savings_base,
        ),
        (
            modelo_109::HOJA_SAVINGS_QUOTA,
            "Cuota íntegra del ahorro",
            statement.savings_quota,
        ),
        (
            layout.double_taxation,
            "Deducción por doble imposición internacional",
            statement.total_foreign_tax_credit,
        ),
        (
            layout.net_quota,
            "Cuota líquida del ahorro",
            statement.net_tax_due,
        ),
    ] {
        boxes.push(FormBox::new(
            "MODELO_109_HOJA_",
            form_name(SpanishTaxRegime::Gipuzkoa),
            "hoja",
            casilla,
            concept,
            value,
        ));
    }

    // Both sheets carry a retenciones box, and the filer sees whichever one the form puts in front
    // of them, so name the ones that exist for the year.
    let withholding_casilla = if layout.anexo3 {
        format!(
            "{} (hoja) / {} (anexo 3)",
            layout.rcm_prepayments,
            modelo_109::ANEXO3_RCM_WITHHOLDING
        )
    } else {
        format!("{} (hoja)", layout.rcm_prepayments)
    };

    FormMapping {
        title: "MODELO 109 — autoliquidación del IRPF de Gipuzkoa",
        header_lines,
        boxes,
        footer_lines: Vec::new(),
        withholding_casilla,
    }
}

fn modelo_100_mapping(statement: &SpanishTaxStatement) -> FormMapping {
    let boxes = [
        (
            modelo_100::INTEREST,
            "Intereses de cuentas y depósitos (rendimientos del capital mobiliario)".to_owned(),
            statement.total_interest_income,
        ),
        (
            modelo_100::DIVIDENDS,
            "Dividendos y participaciones en beneficios (excluida la renta exenta)".to_owned(),
            statement.total_dividend_income - statement.total_dividend_exemption,
        ),
        (
            modelo_100::RCM_EXPENSES,
            "Gastos de administración y depósito (art. 26.1.a)".to_owned(),
            statement.total_deductible_fees,
        ),
        (
            modelo_100::LISTED_CAPITAL_GAINS,
            "Ganancias y pérdidas por transmisión de acciones cotizadas (casillas 0326-0340)"
                .to_owned(),
            statement.gyp_net,
        ),
        (
            modelo_100::SAVINGS_BASE,
            format!(
                "Base imponible del ahorro (tras compensación) — la base liquidable es la casilla \
                 {} y resta el remanente de reducciones que esta herramienta no calcula",
                modelo_100::SAVINGS_BASE_AFTER_REDUCTIONS
            ),
            statement.savings_base,
        ),
        (
            modelo_100::FOREIGN_TAX_CREDIT,
            "Deducción por doble imposición internacional".to_owned(),
            statement.total_foreign_tax_credit,
        ),
    ]
    .into_iter()
    .map(|(casilla, concept, value)| {
        FormBox::new(
            "MODELO_100_",
            form_name(SpanishTaxRegime::Comun),
            "",
            casilla,
            &concept,
            value,
        )
    })
    .collect();

    // The 0326-0340 block is specifically *acciones cotizadas*: 0327 takes one row per operation,
    // 0339 the sum of gains and 0340 the sum of losses. A currency conversion is a transmisión too
    // (LIRPF art. 33) but not of a listed share, so it belongs in the block for otros elementos
    // patrimoniales. The tool posts the group's net figure and says so rather than splitting a
    // mapping it cannot verify against an enacted form.
    let footer_lines = if statement.total_fx_result.is_zero() {
        Vec::new()
    } else {
        vec![
            format!(
                "WARNING: casilla {} is the acciones-cotizadas block. The figure above includes €{} of",
                modelo_100::LISTED_CAPITAL_GAINS,
                super::format_eur(statement.total_fx_result)
            ),
            "foreign-currency conversion results, which are transmissions of a different kind of"
                .to_owned(),
            format!(
                "element (LIRPF art. 33). They belong in apartado F2 under casilla {}, \"otros \
                 elementos",
                modelo_100::OTHER_ELEMENTS
            ),
            "patrimoniales no afectos a actividades economicas\". Split them by hand before entering"
                .to_owned(),
            "either one; the value casillas of that sub-block are not reproduced here.".to_owned(),
        ]
    };

    FormMapping {
        title: "MODELO 100 — declaración del IRPF (AEAT)",
        header_lines: [
            "WARNING: these are the ejercicio-2025 box numbers, read from Anexo I of the",
            "Orden HAC/277/2026 CONSULTATION DRAFT — the AEAT publishes a filing year's",
            "form in the spring of the following one, so no enacted numbering exists yet.",
            "Verify every casilla against your filing year's own form before entering it.",
        ]
        .map(str::to_owned)
        .to_vec(),
        boxes,
        footer_lines,
        withholding_casilla: modelo_100::RCM_WITHHOLDING.to_owned(),
    }
}

