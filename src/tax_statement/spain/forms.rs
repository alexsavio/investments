//! Where each figure goes on the return: Modelo 109 (Gipuzkoa), Modelo 100 (Territorio Común) and
//! Modelo F-93 (Navarra), plus the regime-dependent wording of the compensation and FX rows.
//!
//! One mapping serves every output. A casilla number, the caveat that qualifies it and the label
//! that names it are written once here, so the CSV and the printable report cannot send a filer to
//! two different boxes for the same amount.

use crate::taxes::spain::SpanishTaxRegime;
use crate::types::Decimal;

use super::statement::SpanishTaxStatement;

/// Modelo 109 box numbers, per ejercicio.
///
/// Gipuzkoa publishes no blank numbered form — the return is generated by the Zergabidea platform —
/// so the numbers are read off the Hacienda Foral "Propuesta de autoliquidación" specimens, one per
/// ejercicio (`gipuzkoa.eus/es/web/ogasuna/impuestos/modelo/109/<ejercicio>/propuesta-autoliquidacion`,
/// retrieved 2026-08-11).
///
/// The **Hoja de liquidación** numbering below is stable from ejercicio 2019 through 2025. The
/// deduction block is not: NF 1/2025 renumbered it for ejercicio 2025, moving the deducción por
/// doble imposición internacional from casilla 60 to 70 and the cuota líquida from 64 to 74.
///
/// **Anexo 3 is a different numbering space from the Hoja** — Hoja 28 is the rendimiento neto del
/// capital mobiliario while Anexo 4's own 28 is ganancias — and its internals are confirmed only
/// through ejercicio 2024; the 2025 specimen renumbers them. They are emitted for ejercicios up to
/// 2024 only, under keys that name the sheet they belong to.
mod modelo_109 {
    /// Rendimiento neto del capital mobiliario, base del ahorro.
    pub const HOJA_RCM_NET: &str = "28";
    pub const HOJA_RCM_COMPENSATION: &str = "29";
    /// Ganancias y pérdidas patrimoniales por transmisiones.
    pub const HOJA_CAPITAL_GAINS: &str = "30";
    pub const HOJA_GYP_COMPENSATION: &str = "31";
    pub const HOJA_SAVINGS_BASE: &str = "33";
    pub const HOJA_SAVINGS_QUOTA: &str = "38";

    pub const ANEXO3_RCM_GROSS: &str = "06+16";
    pub const ANEXO3_RCM_EXPENSES: &str = "17";
    /// Retenciones practicadas **en España**. Nothing the tool computes belongs here: an IB
    /// statement's withholding is foreign, and foreign tax is relieved through the deducción por
    /// doble imposición, never as a retención. Named so the warning can point at it.
    pub const ANEXO3_RCM_WITHHOLDING: &str = "07+22";

    /// The part of the form NF 1/2025 renumbered.
    pub struct Layout {
        /// Ejercicio the specimen these numbers come from covers.
        pub ejercicio: i32,
        pub double_taxation: &'static str,
        pub net_quota: &'static str,
        /// Pagos a cuenta del capital mobiliario — Spanish withholding only.
        pub rcm_prepayments: &'static str,
        /// Whether Anexo 3's internals are confirmed for this ejercicio.
        pub anexo3: bool,
    }

    const EJERCICIO_2024: Layout = Layout {
        ejercicio: 2024,
        double_taxation: "60",
        net_quota: "64",
        rcm_prepayments: "67",
        anexo3: true,
    };

    const EJERCICIO_2025: Layout = Layout {
        ejercicio: 2025,
        double_taxation: "70",
        net_quota: "74",
        rcm_prepayments: "77",
        anexo3: false,
    };

    /// The published layout for a filing year. Anything after 2025 gets the 2025 one: the form for a
    /// filing year is published with its campaign, so no later numbering exists yet.
    pub fn layout(year: i32) -> &'static Layout {
        if year <= 2024 {
            &EJERCICIO_2024
        } else {
            &EJERCICIO_2025
        }
    }
}

/// Modelo 100 box numbers for ejercicio 2025.
///
/// Read from Anexo I of the Orden HAC/277/2026 consultation draft — the AEAT form for a filing year
